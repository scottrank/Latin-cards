"""Generate src/cards.js from scripts/deck_source.py.

Card ids are a hash of the Latin front, so they stay stable when cards are
reordered or new batches are added. Fixing a typo on a FRONT changes its id
(that one card's progress restarts); fixing a BACK never does.
"""
import hashlib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from deck_source import DECK  # noqa: E402

cards, seen = [], {}
for lesson, front, back, tag, detail in DECK:
    cid = "c" + hashlib.sha1(front.encode()).hexdigest()[:10]
    if cid in seen:
        sys.exit(f"Duplicate front: {front!r}")
    seen[cid] = front
    card = {"id": cid, "front": front, "back": back, "set": f"Lesson {lesson}", "tag": tag}
    if detail:
        card["detail"] = detail
    cards.append(card)

out = pathlib.Path(__file__).parent.parent / "src" / "cards.js"
out.write_text(
    "// Generated by scripts/build_deck.py from scripts/deck_source.py — edit the source, not this file.\n"
    "export const CARDS = " + json.dumps(cards, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)
lessons = sorted({c["set"] for c in cards}, key=lambda s: int(s.split()[1]))
print(f"{len(cards)} cards across {len(lessons)} lessons -> {out}")
